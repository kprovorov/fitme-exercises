import { z } from "zod";
import { loadLibrary } from "../library/load";
import { serveLibrary } from "../served-library";

const SupabaseUrl = z.url({
  error: "must be the https URL of the Supabase project, e.g. https://<project>.supabase.co",
  protocol: /^https$/,
});

export type GenerateResult =
  | { ok: true; source: string }
  | { ok: false; problems: string[] };

/**
 * Loads and validates the Exercise Library at `root` and turns it into the
 * source of a TypeScript module the API imports: every Exercise with its
 * media URLs resolved on the Supabase project at `supabaseUrl`. An invalid
 * Exercise Library (or URL) gives problems instead, so the build fails.
 */
export const generateLibraryModule = async ({
  root,
  supabaseUrl,
}: {
  root: string;
  supabaseUrl: string | undefined;
}): Promise<GenerateResult> => {
  const url = SupabaseUrl.safeParse(supabaseUrl);
  if (!url.success) {
    return {
      ok: false,
      problems: url.error.issues.map(
        (issue) => `SUPABASE_URL: ${issue.message}`
      ),
    };
  }
  const result = await loadLibrary(root);
  if (!result.ok) {
    return {
      ok: false,
      problems: result.problems.map(
        (problem) => `${problem.file}: ${problem.message}`
      ),
    };
  }

  const library = serveLibrary(result.library, url.data);
  const source = `// Generated by \`pnpm generate\` from the Exercise Library: don't edit.
import type { ServedLibrary } from "../served-library";

export const library: ServedLibrary = ${JSON.stringify(library, null, 2)};
`;
  return { ok: true, source };
};
